import { afterEach, expect, it, vi } from 'vitest'
import { createWorkspaceRecovery } from './workspaceRecovery'
afterEach(() => vi.useRealTimers())

it('retries quickly, then keeps trying on a slower schedule up to a limit, and still allows manual recovery', async () => {
  vi.useFakeTimers()
  const retry = vi.fn().mockResolvedValue(undefined)
  const recovery = createWorkspaceRecovery(retry, { steadyDelayMs: 30000, maxSteadyAttempts: 2 })
  recovery.update(true)
  await vi.advanceTimersByTimeAsync(2000 + 5000 + 15000 + 10)
  expect(retry).toHaveBeenCalledTimes(3)
  await vi.advanceTimersByTimeAsync(30000)
  expect(retry).toHaveBeenCalledTimes(4)
  await vi.advanceTimersByTimeAsync(30000)
  expect(retry).toHaveBeenCalledTimes(5)
  await vi.advanceTimersByTimeAsync(300000)
  expect(retry).toHaveBeenCalledTimes(5)
  await recovery.retry()
  expect(retry).toHaveBeenCalledTimes(6)
  recovery.update(false)
  await recovery.retry()
  await vi.advanceTimersByTimeAsync(300000)
  expect(retry).toHaveBeenCalledTimes(6)
  recovery.stop()
})

it('reloads the page once after the quick retries fail, and then stops scheduling when it does', async () => {
  vi.useFakeTimers()
  const retry = vi.fn().mockResolvedValue(undefined)
  const reload = vi.fn(() => true)
  const recovery = createWorkspaceRecovery(retry, { reload })
  recovery.update(true)
  await vi.advanceTimersByTimeAsync(2000 + 5000 + 14999)
  expect(reload).not.toHaveBeenCalled()
  await vi.advanceTimersByTimeAsync(20)
  expect(retry).toHaveBeenCalledTimes(3)
  expect(reload).toHaveBeenCalledTimes(1)
  await vi.advanceTimersByTimeAsync(300000)
  expect(retry).toHaveBeenCalledTimes(3)
  expect(reload).toHaveBeenCalledTimes(1)
  recovery.stop()
})

it('keeps retrying when the reload is declined (cooldown or offline) and only asks once per failure', async () => {
  vi.useFakeTimers()
  const retry = vi.fn().mockResolvedValue(undefined)
  const reload = vi.fn(() => false)
  const recovery = createWorkspaceRecovery(retry, { reload, steadyDelayMs: 30000, maxSteadyAttempts: 1 })
  recovery.update(true)
  await vi.advanceTimersByTimeAsync(22010)
  expect(reload).toHaveBeenCalledTimes(1)
  await vi.advanceTimersByTimeAsync(30000)
  expect(retry).toHaveBeenCalledTimes(4)
  await vi.advanceTimersByTimeAsync(300000)
  expect(reload).toHaveBeenCalledTimes(1)
  recovery.stop()
})

it('treats a throwing reload as declined', async () => {
  vi.useFakeTimers()
  const retry = vi.fn().mockResolvedValue(undefined)
  const recovery = createWorkspaceRecovery(retry, { reload: () => { throw new Error('blocked') }, steadyDelayMs: 1000, maxSteadyAttempts: 1 })
  recovery.update(true)
  await vi.advanceTimersByTimeAsync(22010 + 1000)
  expect(retry).toHaveBeenCalledTimes(4)
  recovery.stop()
})

it('resets after a successful load so a later failure gets the quick retries and one reload again', async () => {
  vi.useFakeTimers()
  const retry = vi.fn().mockResolvedValue(undefined)
  const reload = vi.fn(() => false)
  const recovery = createWorkspaceRecovery(retry, { reload })
  recovery.update(true)
  await vi.advanceTimersByTimeAsync(22010)
  recovery.update(false)
  recovery.update(true)
  await vi.advanceTimersByTimeAsync(22010)
  expect(reload).toHaveBeenCalledTimes(2)
  recovery.stop()
})

it('does not overlap reconnect and timer work, and cancels on unmount', async () => {
  vi.useFakeTimers()
  let finish
  const retry = vi.fn(() => new Promise((resolve) => { finish = resolve }))
  const recovery = createWorkspaceRecovery(retry)
  recovery.update(true)
  const pending = recovery.retry()
  await recovery.retry()
  await vi.advanceTimersByTimeAsync(60000)
  expect(retry).toHaveBeenCalledTimes(1)
  recovery.stop()
  finish()
  await pending
  await vi.advanceTimersByTimeAsync(60000)
  expect(retry).toHaveBeenCalledTimes(1)
})
